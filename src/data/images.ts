/** Widths generated by `npm run images` (scripts/optimise-images.mjs). */
export const WIDTHS = [400, 600, 800, 1200, 1600] as const;
export const srcSet = (p: Photo) => WIDTHS.map((w) => `/images/${p.name}-${w}.webp ${w}w`).join(', ');
export const src = (p: Photo, width: (typeof WIDTHS)[number] = 1600) => `/images/${p.name}-${width}.webp`;
